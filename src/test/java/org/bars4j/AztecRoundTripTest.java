package org.bars4j;

import static org.junit.jupiter.api.Assertions.assertEquals;

import java.awt.Color;
import java.awt.image.BufferedImage;
import java.util.List;
import java.util.Map;

import com.google.zxing.BinaryBitmap;
import com.google.zxing.DecodeHintType;
import com.google.zxing.Result;
import com.google.zxing.aztec.AztecReader;
import com.google.zxing.client.j2se.BufferedImageLuminanceSource;
import com.google.zxing.common.HybridBinarizer;

import org.bars4j.encode.matrix.AztecEncoder;
import org.bars4j.render.RenderSpec;
import org.bars4j.render.matrix.MatrixRenderer;
import org.bars4j.symbol.MatrixSymbol;
import org.junit.jupiter.api.Test;

/**
 * Renders symbols produced by the self-contained Aztec encoder and decodes them back with ZXing,
 * proving that they are valid Aztec symbols.
 */
class AztecRoundTripTest {

    private static final RenderSpec SPEC = new RenderSpec(1, 70, 2.0, 6, Color.BLACK, Color.WHITE);

    @Test
    void decodedTextEqualsInput() throws Exception {
        List<String> texts = List.of(
                "Bars4J",
                "1",
                "1234567890",
                "HELLO WORLD",
                "Hello, world!",
                "Aztec Code",
                "https://dataprev.gov.br",
                "Aztec gerado pela Bars4J",
                "The quick brown fox jumps over the lazy dog 0123456789",
                "a".repeat(120),
                "1".repeat(300),
                "ISO/IEC 24778 Aztec barcode generated by Bars4J. ".repeat(25));
        AztecEncoder encoder = new AztecEncoder();
        MatrixRenderer renderer = new MatrixRenderer();
        for (String text : texts) {
            MatrixSymbol symbol = encoder.encode(text);
            BufferedImage image = renderer.toImage(symbol, SPEC);
            assertEquals(text, decode(image).getText(), "round-trip failed for '" + text + "'");
        }
    }

    private static Result decode(BufferedImage image) throws Exception {
        BufferedImageLuminanceSource source = new BufferedImageLuminanceSource(image);
        BinaryBitmap bitmap = new BinaryBitmap(new HybridBinarizer(source));
        return new AztecReader().decode(bitmap, Map.<DecodeHintType, Object>of());
    }
}
