package org.bars4j;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.nio.charset.Charset;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;

import com.google.zxing.aztec.encoder.AztecCode;
import com.google.zxing.aztec.encoder.Encoder;
import com.google.zxing.common.BitMatrix;

import org.bars4j.encode.matrix.AztecEncoder;
import org.bars4j.symbol.MatrixSymbol;
import org.junit.jupiter.api.Test;

/**
 * Cross-validates the self-contained Aztec encoder against ZXing, module for module.
 *
 * <p>The inputs are chosen to exercise a range of symbol sizes, covering both compact and full
 * layouts and several layer counts.
 */
class AztecCrossValidationTest {

    @Test
    void matricesMatchZXing() throws Exception {
        AztecEncoder encoder = new AztecEncoder();
        Set<Integer> sizesSeen = new LinkedHashSet<>();
        boolean sawCompact = false;
        boolean sawFull = false;

        for (String text : inputs()) {
            AztecCode expected = Encoder.encode(text, 33, 0, (Charset) null);
            BitMatrix zx = expected.getMatrix();
            MatrixSymbol actual = encoder.encode(text);

            assertEquals(zx.getHeight(), actual.heightInModules(), "height mismatch for '" + text + "'");
            assertEquals(zx.getWidth(), actual.widthInModules(), "width mismatch for '" + text + "'");
            assertEquals(zx.getHeight(), zx.getWidth(), "ZXing produced a non-square symbol");

            for (int y = 0; y < zx.getHeight(); y++) {
                for (int x = 0; x < zx.getWidth(); x++) {
                    if (zx.get(x, y) != actual.module(y, x)) {
                        throw new AssertionError("module mismatch at (" + x + "," + y + ") for '" + text + "'");
                    }
                }
            }

            sizesSeen.add(zx.getWidth());
            if (expected.isCompact()) {
                sawCompact = true;
            } else {
                sawFull = true;
            }
        }

        assertTrue(sizesSeen.size() >= 8,
                "expected the inputs to exercise several symbol sizes, saw " + sizesSeen);
        assertTrue(sawCompact, "expected at least one compact symbol");
        assertTrue(sawFull, "expected at least one full symbol");
    }

    @Test
    void forcedLayersAndEccMatchZXing() throws Exception {
        // A fixed layer count and a non-default ECC percentage must still match ZXing exactly.
        List<String> texts = List.of("Bars4J", "1234567890", "AZTEC".repeat(8));
        int[] layers = {1, -1, 2, -2, 3, 4, 5, 8, 12, 20};
        for (String text : texts) {
            for (int forced : layers) {
                AztecCode expected;
                try {
                    expected = Encoder.encode(text, 25, forced, (Charset) null);
                } catch (IllegalArgumentException e) {
                    // Text does not fit the requested layer count; nothing to compare against.
                    continue;
                }
                BitMatrix zx = expected.getMatrix();
                MatrixSymbol actual = new AztecEncoder(25, forced, null).encode(text);

                assertEquals(zx.getWidth(), actual.widthInModules(),
                        "size mismatch for '" + text + "' layers=" + forced);
                for (int y = 0; y < zx.getHeight(); y++) {
                    for (int x = 0; x < zx.getWidth(); x++) {
                        assertEquals(zx.get(x, y), actual.module(y, x),
                                "module mismatch at (" + x + "," + y + ") for '" + text + "' layers=" + forced);
                    }
                }
            }
        }
    }

    private static List<String> inputs() {
        return List.of(
                "1",
                "A",
                "HELLO",
                "Hello",
                "1234567890",
                "HELLO WORLD",
                "Hello, world!",
                "Aztec Code",
                "Bars4J Aztec",
                "https://dataprev.gov.br",
                "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789",
                "ABCDEFGHIJKLMNOPQRSTUVWXYZ".repeat(3),
                "The quick brown fox jumps over the lazy dog 0123456789",
                "a".repeat(100),
                "a".repeat(200),
                "1".repeat(300),
                "1".repeat(600),
                "AZTEC 24778 ".repeat(40),
                "Mixed Case 123, punctuation; and: symbols.".repeat(20),
                "ISO/IEC 24778 Aztec barcode generated by Bars4J. ".repeat(25));
    }
}
